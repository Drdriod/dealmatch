// Renders docs/STATE_MACHINES.md from the registry. A test compares the file with this output, so
// the doc cannot drift from src/lib/stateMachines.js. Regenerate with `npm run docs:states`.
import { MACHINES, UNCATALOGUED, toMermaid } from './stateMachines.js'

const code = (x) => '`' + x + '`'

export function renderStateMachineDocs() {
  const entries = Object.entries(MACHINES)
  const modelled = entries.filter(([, m]) => m.transitions)
  const catalogued = entries.filter(([, m]) => !m.transitions)
  const out = []
  out.push('<!-- Generated by `npm run docs:states` from src/lib/stateMachines.js. Do not edit by hand. -->')
  out.push('# State machines', '')
  out.push('Every status column in the app, the values it may hold, and who enforces them. The registry in `src/lib/stateMachines.js` only *describes* behaviour; nothing at runtime reads it.', '')
  out.push('**Before you add or change a status:** find its entry here, read its `notes`, change the database CHECK/enum and the code that writes it together, then update the registry and run `npm run docs:states`. If the machine is only catalogued, write its transition table from the code and flip it to modelled.', '')
  out.push(`Modelled: ${modelled.length}. Catalogued (values only): ${catalogued.length}.`, '')
  out.push('Enforcement: `transition-trigger` = the database rejects illegal moves; `conditional-update` = code writes `.eq(status, from)`; `check-constraint` = only the value is checked; `none` = nothing.', '')
  out.push('## Modelled machines', '')
  for (const [name, m] of modelled) {
    out.push(`### ${name}`, '')
    out.push(`${code(m.table + '.' + m.column)} · starts at ${code(m.initial)} · enforced by ${m.enforcedBy.join(', ')}${m.owner ? ` · owner ${code(m.owner)}` : ''}`, '')
    out.push('```mermaid', toMermaid(name), '```', '')
    if (m.notes) out.push(`> ${m.notes}`, '')
  }
  out.push('## Catalogued machines (values only)', '')
  out.push('| Machine | Column | Starts at | Values | Enforced by | Notes |', '| --- | --- | --- | --- | --- | --- |')
  for (const [name, m] of catalogued) {
    out.push(`| ${name} | ${code(m.table + '.' + m.column)} | ${code(m.initial)} | ${Object.keys(m.states).join(', ')} | ${m.enforcedBy.join(', ')} | ${(m.notes || '').replace(/\|/g, '/')} |`)
  }
  out.push('', '## Not catalogued yet', '', 'These columns accept any text. List their values from the code that writes them before relying on them:', '')
  for (const c of UNCATALOGUED) out.push(`- ${code(c)}`)
  out.push('', '## Also implicit: screens', '',
    'Many screens hold a flow in several booleans (`loading`, `saving`, `sent`, `error`). The busiest are `Messages`, `Availability` and the admin `Settings` tab. Prefer one `status` value (`idle | saving | done | error`) in new code so impossible combinations cannot exist.', '')
  out.push('## Check the registry against the database', '',
    'Run in the Supabase SQL editor and compare with the lists above (the CHECK definitions are in the `checks` column):', '', '```sql',
    "select c.table_name, c.column_name,",
    "  (select string_agg(pg_get_constraintdef(k.oid), ' | ') from pg_constraint k",
    "   where k.conrelid = format('public.%I', c.table_name)::regclass and k.contype = 'c'",
    "     and pg_get_constraintdef(k.oid) ilike '%' || c.column_name || '%') as checks",
    'from information_schema.columns c',
    "where c.table_schema = 'public' and c.column_name ~ '(^|_)(status|state)$' order by 1, 2;",
    '```', '')
  return out.join('\n')
}
