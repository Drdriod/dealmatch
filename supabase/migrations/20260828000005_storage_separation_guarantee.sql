-- ============================================================================
-- Private document storage separation - defense in depth (checklist item 11).
--
-- Static review of the schema shows identity-docs and provider-portfolio
-- were already created as separate, non-public buckets with folder-scoped
-- RLS (owner reads/writes their own folder, admin/verifier/agent staff can
-- read any folder, avatars stays the one deliberately public bucket). That
-- part was already correct. This migration is the guarantee, not the fix:
-- it forces both buckets' `public` flag back to false regardless of
-- whatever the Supabase dashboard currently has it set to, so a manual
-- toggle in the dashboard can never silently turn identity documents
-- public without a corresponding code change here to notice.
-- ============================================================================

INSERT INTO storage.buckets (id, name, public)
VALUES ('identity-docs', 'identity-docs', false)
ON CONFLICT (id) DO UPDATE SET public = false;

INSERT INTO storage.buckets (id, name, public)
VALUES ('provider-portfolio', 'provider-portfolio', false)
ON CONFLICT (id) DO UPDATE SET public = false;

-- 'avatars' stays public by design (see F-08 in the original assessment -
-- public profile photos are an intentional product choice), but pin it
-- explicitly too so the intent is recorded in code, not just memory.
INSERT INTO storage.buckets (id, name, public)
VALUES ('avatars', 'avatars', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- ============================================================================
-- CRITICAL: a leftover policy named "Allow public read 107eh68_0" (the name
-- pattern strongly suggests it was auto-generated by the Supabase dashboard
-- UI, not written by hand) had NO bucket_id filter at all - just
-- `USING (true)` on storage.objects with no restriction of any kind.
-- Because RLS permissive policies are OR'd together, this single leftover
-- policy made every object in every bucket in the project publicly
-- readable, including identity-docs and provider-portfolio - completely
-- undermining the private-bucket design confirmed everywhere else in this
-- file. Whatever the "avatars should be public" policy correctly does on
-- purpose, this one did to every bucket by accident.
-- ============================================================================

DROP POLICY IF EXISTS "Allow public read 107eh68_0" ON storage.objects;

-- Its counterpart on the write side: "Allow authenticated users to upload
-- 107eh68_0" had WITH CHECK (auth.uid() IS NOT NULL) and, again, no
-- bucket_id filter - any signed-in user could upload to any path in any
-- bucket, including overwriting another user's file inside identity-docs
-- by targeting their folder directly, bypassing the folder-scoped upload
-- policy that was supposed to be the only way in.
DROP POLICY IF EXISTS "Allow authenticated users to upload 107eh68_0" ON storage.objects;

-- identity-docs had no explicit staff DELETE policy (only the owner could
-- delete their own upload) - a verifier rejecting a submission and asking
-- for a clean re-upload had no supported way to clear the old file first.
DROP POLICY IF EXISTS "Staff delete identity docs" ON storage.objects;
CREATE POLICY "Staff delete identity docs" ON storage.objects
  FOR DELETE TO authenticated
  USING (
    bucket_id = 'identity-docs'
    AND (public.get_my_role() = ANY (ARRAY['admin','verifier','superadmin']) OR public.is_admin_staff())
  );

-- ============================================================================
-- avatars bucket: three more policies (allow_auth_delete, allow_auth_insert,
-- allow_auth_update) checked bucket_id = 'avatars' AND auth.uid() IS NOT
-- NULL, with no folder-ownership check at all. Several correctly-scoped
-- sibling policies already exist ("Avatar user upload", "Avatar user
-- update", "Users upload own avatar") that restrict writes to your own
-- folder - these three sat alongside them and, being permissive, let any
-- signed-in user delete or overwrite ANY other user's avatar regardless.
-- Avatars are public-by-design so this was never an exposure issue, but it
-- is exactly the "User A can edit User B's data" gap directly.
-- ============================================================================

DROP POLICY IF EXISTS allow_auth_delete ON storage.objects;
CREATE POLICY allow_auth_delete ON storage.objects
  FOR DELETE USING (bucket_id = 'avatars' AND (storage.foldername(name))[1] = auth.uid()::text);

DROP POLICY IF EXISTS allow_auth_insert ON storage.objects;
CREATE POLICY allow_auth_insert ON storage.objects
  FOR INSERT WITH CHECK (bucket_id = 'avatars' AND (storage.foldername(name))[1] = auth.uid()::text);

DROP POLICY IF EXISTS allow_auth_update ON storage.objects;
CREATE POLICY allow_auth_update ON storage.objects
  FOR UPDATE USING (bucket_id = 'avatars' AND (storage.foldername(name))[1] = auth.uid()::text);
